/// Recording words that the app's screens and the Recordings widget both show. They live here,
/// outside the app's UI module, so the widget extension can read them.
public enum RecordingLabels {
    /// The name of the app's recordings screen and of the Recordings widget.
    public static let title = "Recordings"
    /// The shortest name of the record control.
    public static let record = "Record"
    /// The mark of a recording filed under no tune.
    public static let unfiled = "Unfiled"
}
